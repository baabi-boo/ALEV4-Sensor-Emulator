function inventory = phase4Fixtures()
%PHASE4FIXTURES Generate 24 small, reproducible structured-noise exposures.
%   INVENTORY = alev4.phase4Fixtures() performs no file I/O. The fixed-name
%   metadata in INVENTORY.fixtures corresponds one-to-one with the enabled
%   results in INVENTORY.results. Sweeps and independent-frame sequence
%   reset/continuation calls retain their explicit metadata separately.
%
%   All parameters are assumed and synthetic, never measured ALEV4 values.
%   Irradiance is photons/(m^2 s nm), exposure is seconds, fixed/read noise
%   and charge are electrons, dark rate is electrons/photosite/second, gain
%   is DN/electron, and PRNU is dimensionless. Reference temperature 293.15 K
%   has no temperature law. EI labels change metadata only. Fixed maps are
%   supplied analytically; their realization IDs are labels, not map hashes.
%
%   The 24 frames are 6-by-8 except a 4-by-5 crop from that full grid. Named
%   local streams preserve caller RNG state. Repeatability is scoped to the
%   same runtime/version. Generation success is not artifact/demo completion:
%   phase4_demo must actually export and read every result before claiming it.
    if nargin ~= 0
        error('ALEV4:Phase4FixturesArguments','phase4Fixtures takes no arguments.');
    end
    caller_rng = rng;
    rng_guard = onCleanup(@() rng(caller_rng)); %#ok<NASGU>
    geometry = alev4.createSensorGeometry(struct('full_grid_size',[6 8], ...
        'pixel_pitch_m',6e-6,'full_grid_cfa_pattern','RGGB'));
    single = singleConfig(false,0);
    dual = dualConfig(false,0,0);
    [column,row] = meshgrid(1:8,1:6);
    photo_rate_e_per_s = 10000+250*row+500*column;
    input = densityForRate(photo_rate_e_per_s,single);
    dark_input = zeros(6,8);
    fixed = alev4.createStructuredNoise([6 8],struct( ...
        'realization_id','ASSUMED-P4-DEMO-MAPS-v1', ...
        'reference_temperature_K',293.15, ...
        'prnu',1+.01*(row-3.5)+.005*(column-4.5), ...
        'dark_shot_noise',false, ...
        'shared',struct('fixed_offset_e',2*(row-3.5)+(column-4.5)), ...
        'single',struct('fixed_offset_e',.25*(row-column)), ...
        'high_gain',struct('fixed_offset_e',.5*row-.25*column), ...
        'low_gain',struct('fixed_offset_e',-.25*row+.5*column)));
    dark = fixed;
    dark.realization_id = 'ASSUMED-P4-DEMO-DARK-v1';
    dark.dark_current_e_per_s = 2+.5*row+.25*column;
    inventory = struct('schema_version','1.0','phase',4, ...
        'fixture_set_id','ASSUMED-P4-DEMO-v1','frame_count',0, ...
        'fixtures',repmat(metadataTemplate(),1,0),'results',{{}}, ...
        'sweeps',repmat(sweepTemplate(),1,0), ...
        'sequences',repmat(sequenceTemplate(),1,0), ...
        'fixture_checks',struct(),'generation_complete',false, ...
        'demo_complete',false,'export_readback_complete',false, ...
        'synthetic',true,'calibrated_alev4',false, ...
        'authentic_arriraw',false,'parameter_classification','assumed', ...
        'reference_temperature_K',293.15, ...
        'temperature_policy','declared applicability only; no temperature law', ...
        'ei_policy','metadata_only_no_exposure_or_gain_mapping', ...
        'reproducibility','same_runtime_and_version_only', ...
        'units',struct('input_irradiance','photons m^-2 s^-1 nm^-1', ...
            'exposure_s','s','charge_and_offsets','electrons', ...
            'noise_magnitude','RMS electrons','dark_current_e_per_s', ...
            'electrons photosite^-1 s^-1','gain_dn_per_e','DN electron^-1', ...
            'black_level_dn','DN','prnu','dimensionless', ...
            'pixel_pitch_m','m','reference_temperature_K','K'), ...
        'runtime',alev4.spatialBundleUtil('runtime'), ...
        'provenance',alev4.sourceProvenance());

    result = alev4.simulateStructuredExposure(input,single,.01,94001,fixed,geometry);
    inventory = add(inventory,'deterministic_prnu_offsets',result, ...
        struct('category','fixed_maps','input_definition','affine_photo_rate_e_per_s'));
    result = alev4.simulateStructuredExposure(dark_input,single,.02,94002,dark,geometry);
    inventory = add(inventory,'dark_short',result, ...
        struct('category','dark','input_definition','zero_irradiance'));
    result = alev4.simulateStructuredExposure(dark_input,single,2,94003,dark,geometry);
    inventory = add(inventory,'dark_long',result, ...
        struct('category','dark','input_definition','zero_irradiance'));
    noisy_dark = dark;
    noisy_dark.dark_shot_noise = true;
    noisy_dark.shared.row_noise_e = .5;
    noisy_dark.single.column_noise_e = .25;
    noisy_dark.single.frame_noise_e = .4;
    result = alev4.simulateStructuredExposure(dark_input,singleConfig(false,.75), ...
        2,94004,noisy_dark,geometry);
    inventory = add(inventory,'dark_noisy',result, ...
        struct('category','dark','input_definition','zero_irradiance'));

    flat_input = densityForRate(50000*ones(6,8),single);
    shared_row = alev4.createStructuredNoise([6 8],struct( ...
        'realization_id','ASSUMED-P4-DEMO-SHARED-ROW-v1', ...
        'dark_shot_noise',false,'shared',struct('row_noise_e',6)));
    result = alev4.simulateStructuredExposure(flat_input,dual,.01,94005,shared_row,geometry);
    inventory = add(inventory,'shared_row_dual',result, ...
        struct('category','structured_dual','input_definition','flat_50000_e_per_s'));
    path_column = alev4.createStructuredNoise([6 8],struct( ...
        'realization_id','ASSUMED-P4-DEMO-PATH-COLUMN-v1', ...
        'dark_shot_noise',false,'high_gain',struct('column_noise_e',4), ...
        'low_gain',struct('column_noise_e',7)));
    result = alev4.simulateStructuredExposure(flat_input,dual,.01,94006,path_column,geometry);
    inventory = add(inventory,'path_column_dual',result, ...
        struct('category','structured_dual','input_definition','flat_50000_e_per_s'));
    mixed = mixedModel(dark);
    noisy_dual = dualConfig(true,.6,1.2);
    result = alev4.simulateStructuredExposure(input,noisy_dual,.01,94007,mixed,geometry);
    inventory = add(inventory,'mixed_dual',result, ...
        struct('category','structured_dual','input_definition','affine_photo_rate_e_per_s'));

    crop = alev4.createSensorGeometry(struct('full_grid_size',[6 8], ...
        'active_roi',[2 2 4 5],'pixel_pitch_m',6e-6,'full_grid_cfa_pattern','RGGB'));
    crop_single = alev4.bindSensorGeometry(single,crop,'derive');
    grid = alev4.createSpatialGrid(struct('x_edges_m',(0:8)*6e-6, ...
        'y_edges_m',(0:6)*6e-6));
    result = alev4.simulateStructuredSpatialExposure(input,grid,crop,crop_single, ...
        .01,94008,fixed,struct('input_stage','post_optics'));
    inventory = add(inventory,'spatial_crop_single',result, ...
        struct('category','spatial','input_definition','affine_photo_rate_e_per_s'));

    sweep_profile = repmat([0 4000 12000 24000 40000 70000 120000 220000],6,1);
    sweep_input = densityForRate(sweep_profile,single);
    sweep_offset = zeros(6,8); sweep_offset(:,1) = -256;
    sweep_model = alev4.createStructuredNoise([6 8],struct( ...
        'realization_id','ASSUMED-P4-DEMO-SWEEP-v1', ...
        'dark_shot_noise',false,'shared',struct('fixed_offset_e',sweep_offset)));
    times = [0 .01 .1];
    labels = {'zero','mid','high'};
    for mode_index = 1:2
        if mode_index == 1
            mode = 'single'; configuration = single; seed = 94100;
        else
            mode = 'dual'; configuration = dual; seed = 94200;
        end
        first = numel(inventory.results)+1;
        sweep_id = [mode '_exposure'];
        for k = 1:numel(times)
            result = alev4.simulateStructuredExposure(sweep_input,configuration, ...
                times(k),seed,sweep_model,geometry);
            inventory = add(inventory,[sweep_id '_' labels{k}],result, ...
                struct('category','exposure_sweep','input_definition', ...
                    'eight_column_photo_rate_e_per_s','sweep_id',sweep_id, ...
                    'sweep_index',k));
        end
        inventory.sweeps(end+1) = sweepMetadata(inventory.fixtures(first:end), ...
            sweep_id,'physical_exposure_s');
    end
    scales = [.25 2];
    gain_names = {'single_gain_low','single_gain_high'};
    first = numel(inventory.results)+1;
    for k = 1:numel(scales)
        gain_single = single;
        gain_single.gain_dn_per_e = single.gain_dn_per_e*scales(k);
        gain_single = alev4.createBaselineSensor(gain_single);
        result = alev4.simulateStructuredExposure(sweep_input,gain_single, ...
            .01,94300,sweep_model,geometry);
        inventory = add(inventory,gain_names{k},result, ...
            struct('category','electronic_gain_sweep','input_definition', ...
                'eight_column_photo_rate_e_per_s','sweep_id','single_electronic_gain', ...
                'sweep_index',k,'electronic_gain_scale',scales(k)));
    end
    inventory.sweeps(end+1) = sweepMetadata(inventory.fixtures(first:end), ...
        'single_electronic_gain','electronic_gain_scale');
    scales = [1 4];
    gain_names = {'dual_gain_low','dual_gain_high'};
    first = numel(inventory.results)+1;
    for k = 1:numel(scales)
        gain_dual = dual;
        gain_dual.high_gain.gain_dn_per_e = dual.high_gain.gain_dn_per_e*scales(k);
        gain_dual.low_gain.gain_dn_per_e = dual.low_gain.gain_dn_per_e*scales(k);
        gain_dual.merge.start_e = dual.merge.start_e/scales(k);
        gain_dual.merge.end_e = dual.merge.end_e/scales(k);
        gain_dual = alev4.createDualGainSensor(gain_dual);
        result = alev4.simulateStructuredExposure(sweep_input,gain_dual, ...
            .01,94400,sweep_model,geometry);
        inventory = add(inventory,gain_names{k},result, ...
            struct('category','electronic_gain_sweep','input_definition', ...
                'eight_column_photo_rate_e_per_s','sweep_id','dual_electronic_gain', ...
                'sweep_index',k,'electronic_gain_scale',scales(k)));
    end
    inventory.sweeps(end+1) = sweepMetadata(inventory.fixtures(first:end), ...
        'dual_electronic_gain','electronic_gain_scale');

    sequence_seed = 4294967200;
    primary = alev4.simulateNoiseSequence(input,noisy_dual,[.02 .02 .02], ...
        sequence_seed,mixed,geometry,struct('start_frame',1,'ei_label',800));
    reset = alev4.simulateNoiseSequence(input,noisy_dual,.02,sequence_seed,mixed, ...
        geometry,struct('start_frame',1,'ei_label',200));
    continuation = alev4.simulateNoiseSequence(input,noisy_dual,[.02 .02], ...
        sequence_seed,mixed,geometry,struct('start_frame',2,'ei_label',[1600 3200]));
    inventory = addSequence(inventory,primary,'primary');
    inventory = addSequence(inventory,reset,'reset');
    inventory = addSequence(inventory,continuation,'continue');
    inventory.frame_count = numel(inventory.results);
    inventory.fixture_checks = checkFixtures(inventory);
    inventory.generation_complete = true;
end

function cfg = singleConfig(shot,read_noise)
    cfg = alev4.createBaselineSensor(struct('image_size',[6 8], ...
        'pixel_pitch_m',6e-6,'wavelength_nm',550,'bin_width_nm',10, ...
        'qe',[1 1 1],'fill_factor',1,'full_well_e',3000, ...
        'shot_noise',shot,'read_noise_e',read_noise,'gain_dn_per_e',1, ...
        'black_level_dn',32,'adc_bits',10,'cfa_pattern','RGGB'));
end

function cfg = dualConfig(shot,high_noise,low_noise)
    common = rmfield(singleConfig(shot,0), ...
        {'read_noise_e','gain_dn_per_e','black_level_dn','adc_bits'});
    cfg = alev4.createDualGainSensor(struct('sensor',common, ...
        'high_gain',struct('gain_dn_per_e',4,'black_level_dn',64, ...
            'adc_bits',12,'read_noise_e',high_noise), ...
        'low_gain',struct('gain_dn_per_e',.5,'black_level_dn',64, ...
            'adc_bits',12,'read_noise_e',low_noise), ...
        'merge',struct('start_e',600,'end_e',900)));
end

function density = densityForRate(rate,cfg)
% QE and fill factor are explicitly one in this analytical fixture family.
    density = rate/(cfg.pixel_pitch_m^2*cfg.bin_width_nm);
end

function model = mixedModel(model)
    model.realization_id = 'ASSUMED-P4-DEMO-MIXED-v1';
    model.dark_shot_noise = true;
    model.shared.row_noise_e = 1.5;
    model.shared.column_noise_e = .75;
    model.shared.frame_noise_e = .5;
    model.high_gain.row_noise_e = .8;
    model.high_gain.column_noise_e = 1.25;
    model.high_gain.frame_noise_e = .3;
    model.low_gain.row_noise_e = 1.1;
    model.low_gain.column_noise_e = 2;
    model.low_gain.frame_noise_e = .4;
    model = alev4.createStructuredNoise([6 8],model);
end

function record = metadataTemplate()
    record = struct('name','','bundle_dir','','category','','result_kind','', ...
        'readout_mode','','input_definition','','image_size',[], ...
        'exposure_s',0,'seed',0,'component_seeds',struct(), ...
        'configuration',struct(),'geometry',struct(),'noise_model',struct(), ...
        'sweep_id','','sweep_index',0,'electronic_gain_scale',1, ...
        'sequence_id','','sequence_role','','sequence_seed',[], ...
        'absolute_frame_index',[],'frame_seed',0,'ei_label',[], ...
        'ei_policy','metadata_only_no_exposure_or_gain_mapping', ...
        'minimum_expected_e',0,'maximum_expected_e',0,'sum_expected_e',0, ...
        'coverage',struct(),'synthetic',true,'calibrated_alev4',false, ...
        'parameter_classification','assumed');
end

function inventory = add(inventory,name,result,extra)
    record = metadataTemplate();
    record.name = name; record.bundle_dir = name;
    record.result_kind = result.result_kind; record.readout_mode = result.readout_mode;
    record.image_size = size(result.readout.expected_electrons);
    record.exposure_s = result.readout.exposure_s;
    record.seed = result.seeds.frame; record.frame_seed = result.seeds.frame;
    record.component_seeds = result.seeds;
    record.configuration = result.configuration;
    record.geometry = result.geometry; record.noise_model = result.noise_model;
    values = result.readout.expected_electrons;
    record.minimum_expected_e = min(values(:));
    record.maximum_expected_e = max(values(:)); record.sum_expected_e = sum(values(:));
    record.coverage = coverage(result);
    names = fieldnames(extra);
    for k = 1:numel(names)
        if ~isfield(record,names{k})
            error('ALEV4:Phase4FixtureMetadata','Unknown internal metadata field.');
        end
        record.(names{k}) = extra.(names{k});
    end
    inventory.fixtures(end+1) = record;
    inventory.results{end+1} = result;
end

function value = coverage(result)
    readout = result.readout;
    value = struct('physical_saturation_pixels',nnz(readout.full_well_saturated), ...
        'single_adc_low_clipped_pixels',0,'single_adc_high_clipped_pixels',0, ...
        'high_adc_low_clipped_pixels',0,'high_adc_high_clipped_pixels',0, ...
        'low_adc_low_clipped_pixels',0,'low_adc_high_clipped_pixels',0, ...
        'high_clipped_low_usable_pixels',0,'merge_transition_pixels',0, ...
        'low_high_clipped_before_well_pixels',0, ...
        'reconstruction_valid_pixels',nnz(readout.reconstruction_valid));
    if strcmp(result.readout_mode,'single')
        value.single_adc_low_clipped_pixels = nnz(readout.adc_low_clipped);
        value.single_adc_high_clipped_pixels = nnz(readout.adc_high_clipped);
    else
        value.high_adc_low_clipped_pixels = nnz(readout.high_gain.adc_low_clipped);
        value.high_adc_high_clipped_pixels = nnz(readout.high_gain.adc_high_clipped);
        value.low_adc_low_clipped_pixels = nnz(readout.low_gain.adc_low_clipped);
        value.low_adc_high_clipped_pixels = nnz(readout.low_gain.adc_high_clipped);
        value.high_clipped_low_usable_pixels = nnz(readout.high_gain.adc_high_clipped & ...
            readout.low_gain.adc_usable & ~readout.full_well_saturated);
        value.merge_transition_pixels = nnz(readout.merged.weight_high>0 & ...
            readout.merged.weight_high<1);
        value.low_high_clipped_before_well_pixels = nnz(readout.low_gain.adc_high_clipped & ...
            ~readout.full_well_saturated);
    end
end

function value = sweepTemplate()
    value = struct('name','','variable','','readout_mode','','fixture_names',{{}}, ...
        'exposures_s',[],'frame_seeds',[],'electronic_gain_scales',[], ...
        'single_gain_dn_per_e',[],'high_gain_dn_per_e',[],'low_gain_dn_per_e',[], ...
        'merge_start_e',[],'merge_end_e',[], ...
        'ei_policy','metadata_only_no_exposure_or_gain_mapping');
end

function value = sweepMetadata(frames,name,variable)
    value = sweepTemplate();
    value.name = name; value.variable = variable;
    value.readout_mode = frames(1).readout_mode;
    value.fixture_names = {frames.name}; value.exposures_s = [frames.exposure_s];
    value.frame_seeds = [frames.seed];
    value.electronic_gain_scales = [frames.electronic_gain_scale];
    for k = 1:numel(frames)
        cfg = frames(k).configuration;
        if strcmp(value.readout_mode,'single')
            value.single_gain_dn_per_e(k) = cfg.gain_dn_per_e;
        else
            value.high_gain_dn_per_e(k) = cfg.high_gain.gain_dn_per_e;
            value.low_gain_dn_per_e(k) = cfg.low_gain.gain_dn_per_e;
            value.merge_start_e(k) = cfg.merge.start_e;
            value.merge_end_e(k) = cfg.merge.end_e;
        end
    end
end

function value = sequenceTemplate()
    value = struct('sequence_id','ASSUMED-P4-DEMO-SEQUENCE-v1','role','', ...
        'fixture_names',{{}},'matches_primary_names',{{}}, ...
        'sequence_seed',0,'frame_indices',[],'frame_seeds',[], ...
        'exposures_s',[],'ei_label',[],'temporal_policy','', ...
        'continuation_policy','','ei_policy','','seed_schedule',struct(), ...
        'rng_generator','','reproducibility','');
end

function inventory = addSequence(inventory,sequence,role)
    value = sequenceTemplate(); value.role = role;
    copied = {'sequence_seed','frame_indices','frame_seeds','exposures_s', ...
        'ei_label','temporal_policy','continuation_policy','ei_policy', ...
        'seed_schedule','rng_generator','reproducibility'};
    for k = 1:numel(copied), value.(copied{k}) = sequence.(copied{k}); end
    for k = 1:sequence.frame_count
        name = sprintf('sequence_%s_%03d',role,sequence.frame_indices(k));
        value.fixture_names{k} = name;
        value.matches_primary_names{k} = sprintf('sequence_primary_%03d',sequence.frame_indices(k));
        inventory = add(inventory,name,sequence.frames{k},struct( ...
            'category','independent_frame_sequence','input_definition', ...
            'affine_photo_rate_e_per_s','sequence_id',value.sequence_id, ...
            'sequence_role',role,'sequence_seed',sequence.sequence_seed, ...
            'absolute_frame_index',sequence.frame_indices(k), ...
            'ei_label',sequence.ei_label(k)));
    end
    inventory.sequences(end+1) = value;
end

function checks = checkFixtures(inventory)
    records = inventory.fixtures; results = inventory.results;
    checks = struct('exact_frame_count',inventory.frame_count==24, ...
        'unique_fixed_names',numel(unique({records.name}))==24, ...
        'single_lower_adc_clip',records(9).coverage.single_adc_low_clipped_pixels>0, ...
        'single_upper_adc_clip',records(10).coverage.single_adc_high_clipped_pixels>0, ...
        'single_physical_saturation',records(11).coverage.physical_saturation_pixels>0, ...
        'dual_lower_adc_clips',records(12).coverage.high_adc_low_clipped_pixels>0 && ...
            records(12).coverage.low_adc_low_clipped_pixels>0, ...
        'dual_high_clip_low_usable',records(13).coverage.high_clipped_low_usable_pixels>0, ...
        'dual_merge_transition',records(13).coverage.merge_transition_pixels>0, ...
        'dual_physical_saturation',records(14).coverage.physical_saturation_pixels>0, ...
        'dual_low_upper_clip_before_well',records(18).coverage.low_high_clipped_before_well_pixels>0, ...
        'fixed_maps_crop_identity',fixedCropMatches(results{1},results{8}), ...
        'sequence_seed_wrap',isequal([records(19:21).seed],[4294967200 4294967264 32]), ...
        'sequence_reset_exact',isequal(results{19},results{22}), ...
        'sequence_continuation_exact',isequal(results{20},results{23}) && ...
            isequal(results{21},results{24}), ...
        'ei_labels_changed_without_physics',records(19).ei_label~=records(22).ei_label && ...
            records(20).ei_label~=records(23).ei_label && ...
            records(21).ei_label~=records(24).ei_label && ...
            isequal(results(19:21),results(22:24)));
    names = fieldnames(checks);
    for k = 1:numel(names)
        if ~checks.(names{k})
            error('ALEV4:Phase4FixtureCoverage','Fixture self-check failed: %s.',names{k});
        end
    end
end

function equal = fixedCropMatches(full_frame,crop_frame)
    rows = 2:5; columns = 2:6;
    equal = isequal(full_frame.noise_model,crop_frame.noise_model) && ...
        isequal(full_frame.active_maps.prnu(rows,columns),crop_frame.active_maps.prnu) && ...
        isequal(full_frame.active_maps.dark_current_e_per_s(rows,columns), ...
            crop_frame.active_maps.dark_current_e_per_s);
    for name = {'shared','single','high_gain','low_gain'}
        equal = equal && isequal(full_frame.active_maps.(name{1}).fixed_offset_e(rows,columns), ...
            crop_frame.active_maps.(name{1}).fixed_offset_e);
    end
end
